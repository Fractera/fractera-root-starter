// THE PARTS MAP OF THE CORE (node step 725-1). The owner, 2026-11-11: «вместо того чтобы взять готовые инструмент ты по какой-то
// причине полез создавать новый и создал говно … Как обновить нашу архитектуру чтобы в любой компонент создав инструмент который можно
// пере использовать сохранил его в базе связи и всегда вызывал».
//
// 🔒 ONE MAP, FOUR KINDS. A ready part is a TOOL (`_tools/<id>/tool.json` → `_tools/TOOLS.json`), a SECTION kind (`sections/SECTIONS.json`),
// a COMPOSITE (a reusable component under `components/` — its card in `components/<folder>/parts.json`) or a PRIMITIVE (one owner per
// kind in `components/ui/` — its card in `components/ui/parts.json`). Before 725 only the first two had a map; the voice textarea and the
// chat lived nowhere an agent could look, and a second, worse copy was built beside them (2026-11-11, 722-4).
// 🔒 THE TRUTH ABOUT A PART LIVES BESIDE IT. A card is in the part's own folder — a description torn away from the code goes stale the
// day the code is edited, silently (the same reason as `tool.json`).
// 🔒 `usedBy` IS MEASURED, NEVER WRITTEN: the imports of the repository are read; a hand list would rot.
// 🔒 THE MAP IS GENERATED BY A COMMAND, the build only checks it is fresh (the same law as the tools and sections maps): a build that
// writes into the working tree hides real edits behind a dirty `git status`.
// Used by: `scripts/build-parts-map.mjs`, `scripts/check-parts-map.mjs`, and `parts_find` (725-2).
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
export const TARGET = join(ROOT, "lib", "parts", "PARTS.json")
const COMPONENTS = join(ROOT, "components")
const KINDS = new Set(["composite", "primitive"])
/** A component imported from at least this many folders outside its own top folder is a shared part and needs a card. */
export const SHARED_AT = 2

const norm = (s) => s.replace(/\r\n/g, "\n")
const readJson = (file) => JSON.parse(norm(readFileSync(file, "utf8")))

/** Every `parts.json` under `components/`, alphabetically — the order never depends on the file system. */
function cardFiles() {
  const out = []
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (e.isDirectory()) walk(join(dir, e.name))
      else if (e.name === "parts.json") out.push(join(dir, e.name))
    }
  }
  walk(COMPONENTS)
  return out
}

/** Source files whose imports are measured (tracked by git — the same set the build compiles). */
function sourceFiles() {
  return execFileSync("git", ["ls-files", "-co", "--exclude-standard", "app", "components", "_tools", "lib", "sections", "providers", "hooks"], { cwd: ROOT, encoding: "utf8" })
    .split("\n")
    .filter((f) => /\.(tsx?|mjs|cjs|jsx?)$/.test(f) && existsSync(join(ROOT, f)))
}

/** `components/form/voice-textarea.client.tsx` → `components/form/voice-textarea.client` (the form an import names). */
const importKey = (path) => path.replace(/\.(tsx?|jsx?)$/, "")
/** The part's own folder: `components/<folder>`, or `components` itself for a file lying directly there. */
const topFolder = (path) => {
  const two = path.split("/").slice(0, 2).join("/")
  return path.split("/").length > 2 && existsSync(join(ROOT, two)) && statSync(join(ROOT, two)).isDirectory() ? two : path.split("/")[0]
}

/** Who imports what: `components/<x>` → the set of importing files. Relative imports inside one folder are not a reuse. */
export function measureImports() {
  const users = new Map()
  for (const f of sourceFiles()) {
    const src = readFileSync(join(ROOT, f), "utf8")
    for (const m of src.matchAll(/(?:from|import)\s*\(?\s*["']@\/((?:components|_tools)\/[^"']+)["']/g)) {
      const key = m[1]
      if (!users.has(key)) users.set(key, new Set())
      users.get(key).add(f)
    }
  }
  return users
}

function validateCard(card, file, problems) {
  const where = relative(ROOT, file)
  const need = (cond, what) => { if (!cond) problems.push(`${where} «${card?.id ?? "?"}»: ${what}`) }
  need(typeof card.id === "string" && /^[a-z0-9-]+$/.test(card.id), "id must be kebab-case")
  need(KINDS.has(card.kind), `kind must be one of ${[...KINDS].join(", ")}`)
  need(typeof card.path === "string" && existsSync(join(ROOT, card.path)), `path «${card.path}» is not a file`)
  need(typeof card.export === "string" && card.export.length > 0, "export names what to import")
  for (const l of ["en", "ru"]) {
    need(typeof card.what?.[l] === "string" && card.what[l].length >= 20, `what.${l} is missing or too short`)
    need(Array.isArray(card.words?.[l]) && card.words[l].length >= 2, `words.${l} needs at least two search words`)
  }
  need(typeof card.how === "string" && card.how.length >= 10, "how says how to use it")
  if (card.replaces !== undefined) need(Array.isArray(card.replaces), "replaces is a list of import patterns")
  if (card.also !== undefined) need(Array.isArray(card.also) && card.also.every((f) => typeof f === "string" && existsSync(join(ROOT, f))), "also lists the other files of one family, each a file")
  if (card.internal !== undefined) need(card.internal === true, "internal is true or absent (a part used inside another part, not taken directly)")
}

/** Collect every part and every problem. Problems are a list, not an exception: the guard names them all at once. */
export function collect() {
  const problems = []
  const users = measureImports()
  const usedBy = (path) => [...(users.get(importKey(path)) ?? [])].filter((f) => topFolder(f) !== topFolder(path) || !f.startsWith("components/")).sort()

  const parts = []
  const seen = new Map()
  for (const file of cardFiles()) {
    let data
    try {
      data = readJson(file)
    } catch (e) {
      problems.push(`${relative(ROOT, file)}: not JSON (${e.message})`)
      continue
    }
    for (const card of data.parts ?? []) {
      validateCard(card, file, problems)
      if (seen.has(card.id)) problems.push(`«${card.id}» is carded twice: ${seen.get(card.id)} and ${relative(ROOT, file)}`)
      seen.set(card.id, relative(ROOT, file))
      if (typeof card.path === "string" && dirname(relative(ROOT, file)) !== topFolder(card.path))
        problems.push(`${relative(ROOT, file)} «${card.id}»: the card must live in the part's own folder (${topFolder(card.path)})`)
      const u = typeof card.path === "string" ? usedBy(card.path) : []
      parts.push({ ...card, usedBy: u })
    }
  }

  // Tools and sections come from their own maps — never a second list of them.
  const tools = existsSync(join(ROOT, "_tools", "TOOLS.json")) ? readJson(join(ROOT, "_tools", "TOOLS.json")).tools ?? [] : []
  for (const t of tools)
    parts.push({ id: `tool-${t.id.replace(/^tool-/, "")}`, kind: "tool", path: `${t.dir}/${t.entry}`, export: "default", title: t.en?.title ?? t.id, what: { en: t.en?.what ?? "", ru: t.ru?.what ?? "" },
      how: t.en?.how ?? "", words: { en: [t.id, ...(t.words?.en ?? [])], ru: [...(t.words?.ru ?? [])] }, needs: t.needs ?? [],
      // Measured like every other part: the files that import anything of `_tools/<id>/` from outside it.
      usedBy: [...new Set([...users].filter(([k]) => k.startsWith(`_tools/${t.id}/`)).flatMap(([, set]) => [...set]))]
        .filter((f) => !f.startsWith(`_tools/${t.id}/`)).sort() })
  // Sections: every KIND of the catalogue (73), described by its own card text and its type (14) — the kind is what a page names.
  const sectionsMap = existsSync(join(ROOT, "sections", "SECTIONS.json")) ? readJson(join(ROOT, "sections", "SECTIONS.json")) : { types: [], kinds: [] }
  const typeOf = new Map((sectionsMap.types ?? []).map((t) => [t.id, t]))
  for (const k of sectionsMap.kinds ?? []) {
    const t = typeOf.get(k.type)
    const firstLine = (k.description ?? "").split("\n").find((l) => l.trim() && !l.startsWith("#"))?.trim() ?? ""
    parts.push({ id: `section-${k.kind}`, kind: "section", path: `sections/kinds/${k.kind}`, export: k.kind,
      what: { en: `${t?.title?.en ?? k.type} section «${k.kind}» (${k.shape}): ${t?.purpose?.en ?? ""}`.trim(),
        ru: `${k.title ?? t?.title?.ru ?? k.kind}${firstLine ? ` — ${firstLine}` : ""}` },
      how: `A page names the kind «${k.kind}» in its language cell with the fields ${k.fields} (skill use-sections).`,
      words: { en: [k.kind, t?.title?.en ?? k.type].filter(Boolean), ru: [k.title ?? k.kind, t?.title?.ru ?? k.type].filter(Boolean) },
      usedBy: [...(k.usedOn ?? [])].sort() })
  }

  // An element's own sections (717): one folder per kind, `components/sections/section-<kind>/` with its README — the first line of the
  // README after its title is the card's text. The core has its catalogue in SECTIONS.json instead.
  const ownSections = join(COMPONENTS, "sections")
  if (existsSync(join(ownSections, "index.ts")))
    for (const d of readdirSync(ownSections, { withFileTypes: true }).filter((e) => e.isDirectory() && e.name.startsWith("section-")).map((e) => e.name).sort()) {
      const readme = existsSync(join(ownSections, d, "README.md")) ? readFileSync(join(ownSections, d, "README.md"), "utf8") : ""
      const line = readme.split("\n").find((l) => l.trim() && !l.startsWith("#") && !l.startsWith("|"))?.trim() ?? d
      const kind = d.slice("section-".length)
      parts.push({ id: d, kind: "section", path: `components/sections/${d}/index.tsx`, export: d, what: { en: line, ru: line },
        how: `A page lists { kind: "${d}", …fields } and PageBody renders it from this element's set (components/sections/index.ts).`,
        words: { en: [kind.replace(/-/g, " "), d], ru: [kind.replace(/-/g, " ")] }, usedBy: [] })
    }

  // Every primitive of `components/ui/` has its card: the closed set of kinds, «one owner per kind» (use-primitives).
  const carded = new Set(parts.flatMap((p) => [p.path, ...(Array.isArray(p.also) ? p.also : [])]).filter(Boolean))
  for (const f of readdirSync(join(COMPONENTS, "ui")).filter((f) => /\.tsx?$/.test(f)).sort())
    if (!carded.has(`components/ui/${f}`)) problems.push(`components/ui/${f}: a primitive without its card in components/ui/parts.json`)

  // A component shared by two or more folders without a card is a part nobody can find — the defect of 722-4.
  for (const [key, set] of users) {
    if (!key.startsWith("components/") || key.startsWith("components/ui/") || /\.i18n$|types?$/.test(key)) continue
    const file = ["tsx", "ts", "jsx"].map((x) => `${key}.${x}`).find((p) => existsSync(join(ROOT, p)))
    if (!file || !file.endsWith("x")) continue
    const folders = new Set([...set].filter((f) => !f.startsWith(topFolder(key) + "/")).map((f) => dirname(f)))
    if (folders.size >= SHARED_AT && !carded.has(file))
      problems.push(`${file}: imported from ${folders.size} folders and has no card — add it to ${topFolder(key)}/parts.json (or keep it in one folder)`)
  }

  // 725-7: a file born as a part says so on its first lines — `// @part <id> — <what>` — and its card with that id follows in the same
  // commit; `// @local — <why>` is the other answer. A declaration without its card is a promise nobody can find.
  const byId = new Map(parts.map((p) => [p.id, p]))
  for (const f of sourceFiles().filter((f) => f.endsWith(".tsx"))) {
    const head = readFileSync(join(ROOT, f), "utf8").split("\n").slice(0, 8).join("\n")
    const m = head.match(/\/\/\s*@part\s+([a-z0-9-]+)/)
    if (!m) continue
    const card = byId.get(m[1])
    if (!card) problems.push(`${f}: declared «@part ${m[1]}» but no card has that id — add it to ${topFolder(f)}/parts.json`)
    else if (card.path !== f) problems.push(`${f}: declared «@part ${m[1]}» but that card points to ${card.path}`)
  }

  // 725-3: `replaces` is a law, not a hint. A file that imports what a card replaces — the bare microphone instead of the voice textarea,
  // the dialog primitive instead of AppDialog, next/image instead of StaticImage — is red, naming the part to take. Allowed: the part's own
  // folder (it wraps the replaced thing), the replaced thing's own folder, and `_tools/` (a tool is a self-contained archive, use-tools).
  for (const card of parts.filter((p) => Array.isArray(p.replaces) && p.replaces.length)) {
    for (const f of sourceFiles()) {
      if (f.startsWith(topFolder(card.path) + "/") || f.startsWith("_tools/")) continue
      const src = readFileSync(join(ROOT, f), "utf8")
      for (const r of card.replaces) {
        const own = r.startsWith("@/") ? topFolder(r.slice(2)) : null
        if (own && f.startsWith(own + "/")) continue
        if (new RegExp(`from\\s+["']${r.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&")}["']`).test(src))
          problems.push(`${f}: imports «${r}» — take ${card.export} (${card.path}) instead; its card says it replaces that (725-3)`)
      }
    }
  }

  const order = { tool: 0, composite: 1, primitive: 2, section: 3 }
  parts.sort((a, b) => order[a.kind] - order[b.kind] || a.id.localeCompare(b.id))
  return { parts, problems }
}

export function render(parts) {
  const counts = {}
  for (const p of parts) counts[p.kind] = (counts[p.kind] ?? 0) + 1
  return JSON.stringify({
    _: "Generated by npm run build:parts-map from components/**/parts.json, _tools/TOOLS.json and sections/SECTIONS.json. Hand edits are lost.",
    counts,
    parts,
  }, null, 2) + "\n"
}
