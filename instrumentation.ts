// ЗАПУСК СЕРВЕРА — ВЗЯТЬ СВЕЖИЕ НАСТРОЙКИ ПРОЕКТА (шаг 299-6).
//
// Толчок элемента «Настройки проекта» приходит только после сохранения. Сайт, который был выключен в момент
// сохранения, иначе жил бы старой копией до следующей правки. Поэтому при каждом запуске (и на сборке — страницы
// предрендерятся уже по свежей копии) сайт спрашивает элемент сам. Не ответил — остаётся прежняя копия, запуск
// не ждёт дольше пяти секунд и не падает.
export async function register() {
  if (process.env.NEXT_RUNTIME !== "nodejs") return
  const { pullProjectSettings } = await import("./lib/project-settings")
  const r = await pullProjectSettings()
  if (r.ok) console.log(`[settings] копия настроек проекта получена (${r.changed ? "изменилась" : "без изменений"})`)
  else if (r.reason !== "no-config-element") console.warn(`[settings] элемент настроек не ответил: ${r.reason} — работаю по прежней копии`)
}
